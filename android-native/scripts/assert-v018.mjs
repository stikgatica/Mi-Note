import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import path from 'node:path';
const stage=path.join(process.cwd(),'stage');
const html=await fs.readFile(path.join(stage,'index.html'),'utf8');
const app=await fs.readFile(path.join(stage,'app.js'),'utf8');
const ui=await fs.readFile(path.join(stage,'landscape-ui.js'),'utf8');
const begin=html.indexOf('<select id="landscapeOrientation">');
const finish=html.indexOf('</select>',begin);
const selector=begin>=0&&finish>begin?html.slice(begin,finish):'';
assert(selector,'No se encontró el selector de orientación');
assert(selector.includes('value="landscape-cw" selected'),'Horizontal derecha no está predeterminado');
assert(selector.includes('value="portrait"'),'Debe conservarse opción vertical A5');
assert(!selector.includes('landscape-ccw'),'No se debe mostrar giro izquierdo');
assert(app.includes("orientation:page()?.orientation||'landscape-cw'"),'La orientación por defecto debe ser horizontal derecha');
assert(app.includes("if((pg.orientation||'landscape-cw')==='landscape-cw')"),'El lienzo no aplicaría giro por defecto');
assert(app.includes("const rot=page()?.orientation||'landscape-cw'"),'El toque no aplicaría giro por defecto');
assert(app.includes("next.orientation=current.orientation||'landscape-cw'"),'La hoja nueva debe adoptar giro derecho');
assert(ui.includes("selectOrientation('landscape-cw')"),'Hojas heredadas a la izquierda deben actualizarse');
assert(!ui.includes("?'landscape-ccw':"),'El control rápido no debe activar giro izquierdo');
console.log('OK V0.18: únicamente vertical y horizontal derecha; predeterminado, trazos y páginas coherentes.');

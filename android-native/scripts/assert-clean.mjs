import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import path from 'node:path';
const root=path.join(process.cwd(),'stage');
const html=await fs.readFile(path.join(root,'index.html'),'utf8');
const css=await fs.readFile(path.join(root,'floating-ui.css'),'utf8');
const mobile=await fs.readFile(path.join(root,'mobile-ui.js'),'utf8');
const floating=await fs.readFile(path.join(root,'floating-ui.js'),'utf8');
assert.match(html,/<body class="minote-android clean-notes">/,'La aplicación debe arrancar en modo limpio');
assert.match(html,/<div id="tvBoardToolbar" class="floating-bar"/,'La barra debe estar visible sin activar proyección');
assert.doesNotMatch(html,/<div id="tvBoardToolbar" hidden/,'No debe comenzar oculta');
assert.match(html,/href="\.\/floating-ui\.css"/);
assert.match(html,/src="\.\/floating-ui\.js"/);
assert.match(css,/clean-notes:not\(\.tv-board\) \.workspace/,'La hoja normal debe tener estilo limpio');
assert.match(css,/background:#101820!important/,'Fondo de pizarra normal y TV');
assert.match(css,/\.toolbar,/,'Barra antigua debe ocultarse');
assert.match(css,/#mobilePageDock,/,'Paginación antigua debe ocultarse');
assert.match(mobile,/minote-android/);
assert.match(floating,/floating-handle/);
assert.match(floating,/floatingLibraryBackdrop/);
console.log('OK: interfaz proyectar-TV flotante siempre activa al iniciar APK.');
